// Generates app/Sources/IonianFlow/IonianTokens.swift from the brand's dist/tokens.flat.json.
// Usage (from the repo root): IONIAN_BRAND=/path/to/brand swift scripts/make-tokens.swift [tokens.flat.json]
// Defaults to ${IONIAN_BRAND:-../brand}/dist/tokens.flat.json.
import Foundation

let root = FileManager.default.currentDirectoryPath
let brand = ProcessInfo.processInfo.environment["IONIAN_BRAND"] ?? "../brand"
let inPath = CommandLine.arguments.count > 1 ? CommandLine.arguments[1] : "\(brand)/dist/tokens.flat.json"
let outPath = "\(root)/app/Sources/IonianFlow/IonianTokens.swift"

guard let data = FileManager.default.contents(atPath: inPath),
      let json = try JSONSerialization.jsonObject(with: data) as? [String: Any],
      let tokens = json["tokens"] as? [String: [String: Any]] else {
    FileHandle.standardError.write(Data("cannot read \(inPath)\n".utf8)); exit(1)
}
let version = json["version"] as? String ?? "?"

func camel(_ s: String) -> String {
    let parts = s.split(whereSeparator: { $0 == "-" || $0 == "." }).map(String.init)
    return parts.enumerated().map { $0.offset == 0 ? $0.element : $0.element.prefix(1).uppercased() + $0.element.dropFirst() }.joined()
}
func swiftName(_ s: String) -> String { let n = camel(s); return n.first!.isNumber ? "s" + n : n }
func num(_ s: String) -> Double {
    Double(s.filter { "0123456789.-".contains($0) }) ?? 0
}
func fmt(_ d: Double) -> String {
    let s = String(format: "%.4f", d)
    var t = s
    while t.hasSuffix("0") { t.removeLast() }
    if t.hasSuffix(".") { t.removeLast() }
    return t.isEmpty ? "0" : t
}

/// "#0b1b2b" or "rgba(11,27,43,.12)" to r, g, b (0...255) and a.
func parseColor(_ s: String) -> (Double, Double, Double, Double) {
    let v = s.trimmingCharacters(in: .whitespaces)
    if v.hasPrefix("#") {
        var h = String(v.dropFirst())
        if h.count == 3 { h = h.map { "\($0)\($0)" }.joined() }
        let n = UInt32(h, radix: 16) ?? 0
        return (Double(n >> 16 & 255), Double(n >> 8 & 255), Double(n & 255), 1)
    }
    let inner = v.drop(while: { $0 != "(" }).dropFirst().dropLast()
    let p = inner.split(separator: ",").map { num(String($0)) }
    return (p[0], p[1], p[2], p.count > 3 ? p[3] : 1)
}
func colorLiteral(_ s: String) -> String {
    let c = parseColor(s)
    return "(\(fmt(c.0)), \(fmt(c.1)), \(fmt(c.2)), \(fmt(c.3)))"
}

struct Layer { var x, y, blur, spread: Double; var color: String }
func parseShadow(_ s: String) -> [Layer] {
    var parts: [String] = [], cur = "", depth = 0
    for ch in s {
        if ch == "(" { depth += 1 } else if ch == ")" { depth -= 1 }
        if ch == "," && depth == 0 { parts.append(cur); cur = "" } else { cur.append(ch) }
    }
    parts.append(cur)
    return parts.map { part in
        let p = part.trimmingCharacters(in: .whitespaces)
        let at = p.range(of: "rgba(")!.lowerBound
        let n = p[..<at].split(separator: " ").map { num(String($0)) }
        return Layer(x: n[0], y: n[1], blur: n.count > 2 ? n[2] : 0, spread: n.count > 3 ? n[3] : 0, color: String(p[at...]))
    }
}
func layerLiteral(_ l: Layer) -> String {
    let c = parseColor(l.color)
    return ".init(color: Color(.sRGB, red: \(fmt(c.0 / 255)), green: \(fmt(c.1 / 255)), blue: \(fmt(c.2 / 255)), opacity: \(fmt(c.3))), "
        + "radius: \(fmt(l.blur / 2)), x: \(fmt(l.x)), y: \(fmt(l.y)), spread: \(fmt(l.spread)))"
}

func ids(_ prefix: String) -> [String] { tokens.keys.filter { $0.hasPrefix(prefix) }.sorted() }
func light(_ id: String) -> String { tokens[id]!["light"] as! String }

var o = """
// GENERATED by scripts/make-tokens.swift from ionian-brand \(version). Do not edit.
import AppKit
import SwiftUI

"""

// Colors
o += "\n// MARK: - Color\n\nenum IonianColor {\n"
o += """
    private static func dynamic(_ light: (CGFloat, CGFloat, CGFloat, CGFloat), _ dark: (CGFloat, CGFloat, CGFloat, CGFloat)) -> NSColor {
        func make(_ c: (CGFloat, CGFloat, CGFloat, CGFloat)) -> NSColor {
            NSColor(srgbRed: c.0 / 255, green: c.1 / 255, blue: c.2 / 255, alpha: c.3)
        }
        let l = make(light), d = make(dark)
        return NSColor(name: nil) { $0.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? d : l }
    }

"""
let colorIds = ids("color.")
for id in colorIds {
    let t = tokens[id]!
    let l = t["light"] as! String, d = (t["dark"] as? String) ?? l
    o += "    static let \(swiftName(String(id.dropFirst(6)))) = dynamic(\(colorLiteral(l)), \(colorLiteral(d)))\n"
}
o += "}\n\nextension Color {\n"
for id in colorIds {
    let n = swiftName(String(id.dropFirst(6)))
    o += "    static let \(n) = Color(nsColor: IonianColor.\(n))\n"
}
o += "}\n"

// Scalars
func scalarEnum(_ title: String, _ prefix: String, _ type: String, skip: Set<String> = [], value: (String) -> String = { fmt(num($0)) }) {
    o += "\nenum \(title) {\n"
    for id in ids(prefix) where !skip.contains(id) {
        o += "    static let \(swiftName(String(id.dropFirst(prefix.count)))): \(type) = \(value(light(id)))\n"
    }
    o += "}\n"
}
o += "\n// MARK: - Space, radius, focus, blur, motion\n"
scalarEnum("Space", "space.", "CGFloat")
scalarEnum("Radius", "radius.", "CGFloat", skip: ["radius.icon"])
o += "\nextension Radius {\n    /// App icon corner as a fraction of the icon size.\n    static let icon: CGFloat = \(fmt(num(light("radius.icon")) / 100))\n}\n"
scalarEnum("FocusRing", "focus.", "CGFloat")
scalarEnum("Blur", "blur.", "CGFloat")
scalarEnum("MotionDuration", "motion.duration.", "TimeInterval", value: { v in
    v.hasSuffix("ms") ? fmt(num(v) / 1000) : fmt(num(v))
})

// Type
o += """

// MARK: - Type

enum IonianFamily { case display, sans, mono }

struct IonianTextStyle {
    var family: IonianFamily
    var size: CGFloat
    var weight: CGFloat
    /// Line height as a multiple of the size.
    var lineHeight: CGFloat
    /// Tracking in em.
    var tracking: CGFloat
    var uppercase: Bool
}

enum IonianType {

"""
for id in ids("type.") {
    let t = tokens[id]!
    let desc = t["light"] as! String
    let family = desc.hasPrefix("Funnel Display") ? "display" : desc.hasPrefix("Funnel Sans") ? "sans" : "mono"
    var size = num(t["fontSize"] as! String)
    if let fluid = t["fluid"] as? String, let r = fluid.range(of: "clamp(") {
        size = num(String(fluid[r.upperBound...].prefix(while: { $0 != "p" })))
    }
    o += "    static let \(swiftName(String(id.dropFirst(5)))) = IonianTextStyle(family: .\(family), size: \(fmt(size)), "
        + "weight: \(fmt(num("\(t["fontWeight"] ?? 400)"))), lineHeight: \(fmt(num("\(t["lineHeight"] ?? 1.5)"))), "
        + "tracking: \(fmt(num(t["letterSpacing"] as? String ?? "0"))), uppercase: \(desc.contains("uppercase")))\n"
}
o += "}\n"

// Shadows
o += """

// MARK: - Shadow

struct IonianShadowLayer {
    var color: Color
    /// CSS blur / 2.
    var radius: CGFloat
    var x: CGFloat
    var y: CGFloat
    var spread: CGFloat
}

struct IonianShadow {
    var light: [IonianShadowLayer]
    var dark: [IonianShadowLayer]
    func layers(dark isDark: Bool) -> [IonianShadowLayer] { isDark ? dark : light }
}

enum IonianShadows {

"""
for id in ids("shadow.") {
    let t = tokens[id]!
    let l = parseShadow(t["light"] as! String).map(layerLiteral).joined(separator: ", ")
    let d = parseShadow((t["dark"] as? String) ?? (t["light"] as! String)).map(layerLiteral).joined(separator: ", ")
    o += "    static let \(swiftName(String(id.dropFirst(7)))) = IonianShadow(\n        light: [\(l)],\n        dark: [\(d)])\n"
}
o += "}\n"

try o.write(toFile: outPath, atomically: true, encoding: .utf8)
print("wrote \(outPath) (brand \(version))")
